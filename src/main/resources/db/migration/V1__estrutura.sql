-- V1 · Estrutura inicial do AgendaSaúde.
-- Migrações são imutáveis depois de aplicadas: mudanças futuras entram como V3, V4…

CREATE TABLE medico (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(120) NOT NULL,
    especialidade VARCHAR(80)  NOT NULL,
    crm           VARCHAR(20)  NOT NULL UNIQUE
);

CREATE TABLE paciente (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE
);

CREATE TABLE consulta (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id   BIGINT      NOT NULL REFERENCES medico (id),
    paciente_id BIGINT      NOT NULL REFERENCES paciente (id),
    inicio      TIMESTAMP   NOT NULL,
    status      VARCHAR(20) NOT NULL CHECK (status IN ('AGENDADA', 'CANCELADA')),
    criada_em   TIMESTAMP   NOT NULL
);

-- T4/T8 · Última barreira contra agendamento duplo, mesmo com requisições simultâneas.
-- Índices PARCIAIS: só valem para consultas AGENDADAS, então cancelar libera o horário.
CREATE UNIQUE INDEX uk_consulta_medico_horario   ON consulta (medico_id, inicio)   WHERE status = 'AGENDADA';
CREATE UNIQUE INDEX uk_consulta_paciente_horario ON consulta (paciente_id, inicio) WHERE status = 'AGENDADA';

-- T10 · A agenda do dia filtra por médico + intervalo de horário.
CREATE INDEX ix_consulta_medico_inicio ON consulta (medico_id, inicio);
